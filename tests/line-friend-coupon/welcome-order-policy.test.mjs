import assert from "node:assert/strict";
import {calculateWelcomeOrder as calc} from "./welcome-order-policy.mjs";
const base={couponCode:"WELCOME50",eventService:"city",eventEligible:true,ticketPrice:600,quantity:1,now:"2026-10-20T10:00:00+08:00"};
const q=(x={})=>calc({...base,...x});
assert.deepEqual([q().gross,q().discount,q().total],[600,50,550]);
assert.deepEqual([q({quantity:2}).gross,q({quantity:2}).discount,q({quantity:2}).total],[1200,100,1100]);
assert.deepEqual([q({quantity:3}).gross,q({quantity:3}).discount,q({quantity:3}).total],[1800,150,1650]);
assert.equal(q({couponCode:""}).total,600);
assert.equal(q({couponCode:"FRIEND50"}).reason,"invalid_code");
assert.equal(q({eventService:"temple"}).reason,"not_eligible");
assert.equal(q({eventEligible:false}).reason,"not_eligible");
assert.equal(q({ticketPrice:0}).reason,"free_ticket");
assert.equal(q({otherDiscountApplied:true}).reason,"cannot_stack");
assert.equal(q({ticketPrice:30,quantity:2}).total,0);
assert.equal(q({now:"2026-10-19T23:59:59+08:00"}).reason,"not_started");
assert.equal(q({now:"2027-01-01T00:00:00+08:00"}).reason,"expired");
assert.equal(q({now:"2026-12-31T23:59:59+08:00"}).discount,50);
assert.throws(()=>q({quantity:0}),/invalid_ticket/);
assert.throws(()=>q({ticketPrice:-1}),/invalid_ticket/);
assert.throws(()=>q({now:"not a date"}),/invalid_date/);
console.log("16 first-phase server policy assertions passed");
