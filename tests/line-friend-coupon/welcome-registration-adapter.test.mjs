import assert from "node:assert/strict";
import {prepareWelcomeRegistration as prepare} from "./welcome-registration-adapter.mjs";
const activity={published:true,status:"open",service:"city",welcome50_enabled:true,max_per_registration:10,ticket_options:[{code:"REG",label:"一般票",unit_price:600,active:true},{code:"FREE",label:"免費票",unit_price:0,active:true}]};
const base={activity,ticketCode:"REG",quantity:1,now:"2026-10-20T10:00:00+08:00"};
const run=(patch={})=>prepare({...base,...patch});
assert.deepEqual([run().original_total,run().promotion_discount,run().total_amount],[600,0,600]);
assert.deepEqual([run({couponCode:"WELCOME50"}).original_total,run({couponCode:"WELCOME50"}).promotion_discount,run({couponCode:"WELCOME50"}).total_amount],[600,50,550]);
assert.equal(run({couponCode:"WELCOME50",quantity:2}).total_amount,1100);
assert.equal(run({couponCode:"WELCOME50",quantity:3}).total_amount,1650);
assert.equal(run({couponCode:"WELCOME50"}).promotion_code,"WELCOME50");
assert.equal(run().promotion_code,null);
assert.throws(()=>run({couponCode:"wrong"}),/coupon_invalid_code/);
assert.throws(()=>run({couponCode:"WELCOME50",activity:{...activity,welcome50_enabled:false}}),/coupon_not_eligible/);
assert.throws(()=>run({couponCode:"WELCOME50",activity:{...activity,service:"temple"}}),/coupon_not_eligible/);
assert.throws(()=>run({couponCode:"WELCOME50",ticketCode:"FREE"}),/coupon_free_ticket/);
assert.throws(()=>run({couponCode:"WELCOME50",now:"2027-01-01T00:00:00+08:00"}),/coupon_expired/);
assert.throws(()=>run({couponCode:"WELCOME50",activity:{...activity,ticket_options:[{code:"REG",unit_price:600,other_coupon_applied:true}]}}),/coupon_cannot_stack/);
assert.throws(()=>run({quantity:11}),/quantity_limit/);
assert.throws(()=>run({quantity:0}),/invalid_quantity/);
assert.throws(()=>run({ticketCode:"UNKNOWN"}),/invalid_ticket/);
assert.throws(()=>run({activity:{...activity,published:false}}),/event_not_open/);
assert.equal(run({activity:{...activity,welcome50_enabled:false}}).total_amount,600);
assert.equal(run({activity:{...activity,service:"temple"}}).total_amount,600);
assert.throws(()=>run({activity:{...activity,ticket_options:[{code:"REG",unit_price:-50}]}}),/invalid_ticket_price/);
console.log("19 isolated registration adapter assertions passed");
