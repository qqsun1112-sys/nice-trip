import assert from "node:assert/strict";
import {quoteFriendCoupon as quote} from "./quote.mjs";
const at=(s)=>new Date(s+"T04:00:00Z");
const E=(id)=>({verified:true,used:false,token:"token-"+id,personId:"person-"+id});
const base={unitPrice:750,quantity:1,service:"city",now:at("2026-10-20")};
assert.deepEqual([quote({...base,entitlements:[E(1)]}).gross,quote({...base,entitlements:[E(1)]}).discount,quote({...base,entitlements:[E(1)]}).total],[750,50,700]);
assert.equal(quote({...base,unitPrice:500,entitlements:[E(1)]}).total,450);
assert.equal(quote({...base,quantity:2,entitlements:[E(1)]}).total,1450);
assert.equal(quote({...base,quantity:2,entitlements:[E(1),E(2)]}).total,1400);
assert.equal(quote({...base,quantity:2,entitlements:[E(1),E(1)]}).discount,50);
assert.equal(quote({...base,quantity:2,entitlements:[E(1),{...E(2),personId:E(1).personId}]}).discount,50);
assert.equal(quote({...base,service:"temple",entitlements:[E(1)]}).discount,0);
assert.equal(quote({...base,unitPrice:0,payment:"free",entitlements:[E(1)]}).discount,0);
assert.equal(quote({...base,entitlements:[{...E(1),used:true}]}).discount,0);
assert.equal(quote({...base,entitlements:[{...E(1),verified:false}]}).discount,0);
assert.equal(quote({...base,entitlements:[{...E(1),expiresAt:"2026-10-19"}]}).discount,0);
assert.equal(quote({...base,now:at("2027-01-01"),entitlements:[E(1)]}).discount,0);
assert.equal(quote({...base,now:at("2026-12-31"),entitlements:[E(1)]}).discount,50);
assert.equal(quote({...base,now:at("2026-10-19"),entitlements:[E(1)]}).discount,0);
assert.equal(quote({...base,unitPrice:30,entitlements:[E(1)]}).total,0);
assert.throws(()=>quote({...base,quantity:0}),/invalid_ticket/);
console.log("16 isolated pricing assertions passed");
