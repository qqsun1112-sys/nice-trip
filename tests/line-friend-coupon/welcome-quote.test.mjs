import assert from "node:assert/strict";
import {quoteWelcome} from "./welcome-quote.mjs";
const base={unitPrice:600,quantity:1,service:"city",code:"WELCOME50",at:"2026-10-20T12:00:00+08:00"};
const q=(changes={})=>quoteWelcome({...base,...changes});
assert.equal(q().provisionalTotal,550);
assert.equal(q({quantity:2}).provisionalTotal,1150);
assert.equal(q({quantity:3}).provisionalTotal,1750);
assert.equal(q({quantity:20}).provisionalDiscount,50);
assert.equal(q({code:" welcome50 "}).provisionalDiscount,50);
assert.equal(q({code:""}).provisionalTotal,600);
assert.equal(q({code:"FRIEND50"}).provisionalDiscount,0);
assert.equal(q({service:"temple"}).provisionalDiscount,0);
assert.equal(q({unitPrice:0}).provisionalDiscount,0);
assert.equal(q({unitPrice:30}).provisionalDiscount,30);
assert.equal(q({at:"2026-10-19T23:59:59+08:00"}).provisionalDiscount,0);
assert.equal(q({at:"2026-10-20T00:00:00+08:00"}).provisionalDiscount,50);
assert.equal(q({at:"2026-12-31T23:59:59+08:00"}).provisionalDiscount,50);
assert.equal(q({at:"2027-01-01T00:00:00+08:00"}).provisionalDiscount,0);
assert.equal(q().redeemable,false);
assert.equal(q().verified,false);
assert.throws(()=>q({quantity:0}),/invalid_ticket/);
assert.throws(()=>q({quantity:21}),/invalid_ticket/);
console.log("18 phase-one WELCOME50 preview assertions passed");
