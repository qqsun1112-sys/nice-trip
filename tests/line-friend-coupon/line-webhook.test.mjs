import assert from "node:assert/strict";
import {createHmac} from "node:crypto";
import {verifyLineWebhookSignature,extractFollowCandidates} from "./line-webhook.mjs";
const secret="test-only-secret";
const sign=s=>createHmac("sha256",secret).update(s).digest("base64");
const raw=JSON.stringify({events:[{type:"follow",source:{type:"user",userId:"Utest"},timestamp:123,webhookEventId:"evt1"},{type:"message",source:{userId:"Uother"}}]});
assert.equal(verifyLineWebhookSignature(raw,sign(raw),secret),true);
assert.equal(verifyLineWebhookSignature(raw+" ",sign(raw),secret),false);
assert.equal(verifyLineWebhookSignature(raw,sign(raw),"wrong"),false);
assert.equal(verifyLineWebhookSignature(raw,"invalid",secret),false);
assert.equal(verifyLineWebhookSignature(raw,sign(raw),""),false);
assert.equal(extractFollowCandidates(raw,sign(raw),secret).length,1);
assert.equal(extractFollowCandidates(raw,sign(raw),secret)[0].userId,"Utest");
assert.throws(()=>extractFollowCandidates(raw,sign(raw),"wrong"),/invalid_signature/);
const bad="{invalid";assert.throws(()=>extractFollowCandidates(bad,sign(bad),secret),/invalid_json/);
const noEvents="{}";assert.throws(()=>extractFollowCandidates(noEvents,sign(noEvents),secret),/invalid_events/);
const missing=JSON.stringify({events:[{type:"follow",source:{}}]});
assert.equal(extractFollowCandidates(missing,sign(missing),secret).length,0);
console.log("11 LINE webhook verification assertions passed");
