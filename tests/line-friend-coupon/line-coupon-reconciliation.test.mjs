import assert from "node:assert/strict";
import {assessLineCoupon as check} from "./line-coupon-reconciliation.mjs";
const base={participantCount:2,unitPrice:500};
const ordinary=check(base);
assert.equal(ordinary.status,"standard");
assert.equal(ordinary.canSubmit,true);
assert.equal(ordinary.total,1000);
assert.equal(ordinary.discount,0);
const requested=check({...base,promotionRequested:true});
assert.equal(requested.status,"verification_required");
assert.equal(requested.canSubmit,false);
assert.equal(requested.requiresConfirmation,true);
const claim=(person,id)=>({serverVerified:true,participantId:person,lineCouponId:id});
const one=check({...base,promotionRequested:true,verifiedClaims:[claim("p1","c1")]});
assert.equal(one.verifiedParticipants,1);
assert.equal(one.canSubmit,false);
const duplicate=check({...base,promotionRequested:true,verifiedClaims:[claim("p1","c1"),claim("p1","c2"),claim("p2","c1")]});
assert.equal(duplicate.verifiedParticipants,1);
const full=check({...base,promotionRequested:true,verifiedClaims:[claim("p1","c1"),claim("p2","c2")]});
assert.equal(full.status,"quote_only");
assert.equal(full.discount,100);
assert.equal(full.total,900);
assert.equal(full.canSubmit,false);
assert.equal(full.requiresAtomicRedemption,true);
assert.equal(check({...base,promotionRequested:true,campaignActive:false}).status,"ineligible");
assert.equal(check({...base,promotionRequested:true,service:"meditation"}).status,"ineligible");
assert.equal(check({...base,promotionRequested:true,verifiedClaims:[{participantId:"p1",lineCouponId:"c1"}]}).verifiedParticipants,0);
assert.equal(check({...base,promotionRequested:true,verifiedClaims:[{...claim("p1","c1"),redeemed:true}]}).verifiedParticipants,0);
assert.throws(()=>check({participantCount:0,unitPrice:500}),/invalid_ticket/);
console.log("18 LINE reconciliation assertions passed");
